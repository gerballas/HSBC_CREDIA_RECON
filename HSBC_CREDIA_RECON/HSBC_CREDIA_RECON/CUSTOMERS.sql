  JOIN MG_CUSTOMER_INTER mci ON mci.PRFT_CUST_ID = n.Customer_Code
  JOIN HUB_MT_SSCUSTP s ON TRIM(s.CUSTOMER_CODE) = TRIM(mci.CUSTOMER_CODE)

