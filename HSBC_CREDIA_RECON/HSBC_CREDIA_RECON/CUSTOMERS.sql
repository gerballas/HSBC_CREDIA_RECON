          FROM NCIS_Customers n1
          JOIN MG_CUSTOMER_INTER mci1 ON mci1.PRFT_CUST_ID = n1.Customer_Code
          JOIN HUB_MT_SSCUSTP s1 ON TRIM(s1.CUSTOMER_CODE) = TRIM(mci1.CUSTOMER_CODE)) TOT1 WHERE TRIM(TO_CHAR(n.Branch_Code)) <> TRIM(TO_CHAR(s.ZGDCB))
    OR (n.Branch_Code IS NULL AND s.ZGDCB IS NOT NULL)
    OR (n.Branch_Code IS NOT NULL AND s.ZGDCB IS NULL)
 GROUP BY TOT1.RESULT_TOTAL

